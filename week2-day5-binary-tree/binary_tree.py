class Node:
  def __init__(self,data):
    self.data=data
    self.left=None
    self.right=None

  def search(self, value):
     if self.data == value:
         return True

     if self.left:
        if self.left.search(value):
          return True

     if self.right:
        if self.right.search(value):
          return True
     return False

