class Node:
  def __init__(self,data):
    self.data=data
    self.left=None
    self.right=None

  def insert(self, data):
     queue = [self]

     while queue:
           current = queue.pop(0)

           if current.left is None:
              current.left = Node(data)
              return

           else:
              queue.append(current.left)

           if current.right is None:
             current.right = Node(data)
             return

           else:
             queue.append(current.right)

  def level_order_traversal(self):
    if not self:
      print("Tree is empty")
      return

    q = [self]
    result = []
    while q:
      node = q.pop(0)
      result.append(node.data)

      if node.left:
        q.append(node.left)
      if node.right:
        q.append(node.right)
    print("Tree elements (level-order traversal):")
    print(result)


